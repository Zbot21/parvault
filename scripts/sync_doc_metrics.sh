#!/usr/bin/env bash
# ==============================================================================
# sync_doc_metrics.sh — Zero-LLM Documentation Metrics Sync & Drift Check
# ==============================================================================
# Rewrites every marked value in a repository's Markdown files from one
# metrics file, so numbers in docs never need hand or LLM edits:
#
#   Kani harnesses: <!-- metric:kani_harnesses -->17<!-- /metric -->
#
# Format and rules: ../references/doc_metrics_sync.md
#
# Modes: write (default), --check (CI drift check), --list (all markers).
# --generate runs the repository's own generator (default
# scripts/gen_metrics.sh) and refreshes the generated block of the metrics
# file before writing or checking.
#
# Exit codes: 0 in sync (or written / listed), 1 drift found by --check,
#             2 usage, metrics, marker, file, or generator error. Nothing is
#             written when any error is found.
# ==============================================================================

set -euo pipefail

MODE="write"
GENERATE=0
METRICS=""
GENERATOR=""
REPO=""

usage() {
  cat <<'EOF'
Usage: sync_doc_metrics.sh [OPTIONS] <repo-path>

Options:
  --check              Report every marker whose text differs from the metrics
                       file (file:line) and exit 1. Writes nothing.
  --list               Print every marker as 'file:line: key = text'.
  --generate           Run the generator first and refresh the generated block
                       of the metrics file (with --check: report a stale block).
  --metrics <file>     Metrics file. Default: <repo-path>/docs/metrics.txt
  --generator <file>   Generator script. Default: <repo-path>/scripts/gen_metrics.sh
  -h, --help           Show this help message and exit.
EOF
}

die() {
  echo "ERROR: $*" >&2
  exit 2
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) MODE="check"; shift ;;
    --list) MODE="list"; shift ;;
    --generate) GENERATE=1; shift ;;
    --metrics)
      [[ $# -ge 2 ]] || die "--metrics requires a file argument."
      METRICS="$2"
      shift 2
      ;;
    --generator)
      [[ $# -ge 2 ]] || die "--generator requires a file argument."
      GENERATOR="$2"
      shift 2
      ;;
    -h|--help) usage; exit 0 ;;
    -*)
      echo "ERROR: Unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
    *)
      [[ -z "$REPO" ]] || die "Exactly one repository path is allowed."
      REPO="$1"
      shift
      ;;
  esac
done

[[ -n "$REPO" ]] || { usage >&2; die "A repository path is required."; }
[[ -d "$REPO" ]] || die "Directory does not exist: $REPO"
[[ "$MODE" != list || "$GENERATE" -eq 0 ]] || die "--list cannot be combined with --generate."
command -v python3 >/dev/null 2>&1 || die "python3 is required."
REPO="$(git -C "$REPO" rev-parse --show-toplevel 2>/dev/null)" || die "Not a git work tree: $REPO"

abs_path() { if [[ "$1" == /* ]]; then printf '%s' "$1"; else printf '%s/%s' "$REPO" "$1"; fi; }
METRICS="$(abs_path "${METRICS:-docs/metrics.txt}")"
GENERATOR="$(abs_path "${GENERATOR:-scripts/gen_metrics.sh}")"

WORKDIR="$(mktemp -d)" || die "mktemp failed."
trap 'rm -rf "$WORKDIR"' EXIT

git -C "$REPO" ls-files -z --cached --others --exclude-standard -- '*.md' > "$WORKDIR/md-files" \
  || die "git ls-files failed; refusing to check a partial file list."

: > "$WORKDIR/generated"
if [[ "$GENERATE" -eq 1 ]]; then
  [[ -f "$GENERATOR" ]] || die "--generate: generator not found: $GENERATOR"
  (cd "$REPO" && bash "$GENERATOR") > "$WORKDIR/generated" \
    || die "generator failed (exit $?): $GENERATOR"
  [[ -s "$WORKDIR/generated" ]] || die "generator printed no metrics: $GENERATOR"
fi

python3 - "$REPO" "$METRICS" "$MODE" "$GENERATE" "$WORKDIR/generated" "$GENERATOR" "$WORKDIR/md-files" <<'PY'
import os
import re
import sys
import tempfile


def _fail_closed(exc_type, exc, tb):
    # Any unexpected exception is an error (exit 2), never drift (exit 1).
    print(f"ERROR: internal failure: {exc_type.__name__}: {exc}", file=sys.stderr)
    sys.exit(2)


sys.excepthook = _fail_closed

repo, metrics_path, mode, generate, gen_out, generator, md_list = sys.argv[1:8]
generate = generate == "1"

KEY = r"[A-Za-z0-9_.-]+"
ENTRY_RE = re.compile(rf"^({KEY})[ \t]*=[ \t]*(.*?)[ \t]*$")
GEN_BEGIN = "# >>> generated by sync_doc_metrics.sh --generate; do not edit"
GEN_END = "# <<< end generated"
CODESPAN_RE = re.compile(r"(?<!`)(`+)(?!`)(.+?)(?<!`)\1(?!`)")
COMMENT_RE = re.compile(r"<!--(.*?)-->")
OPEN_RE = re.compile(rf"^\s*metric:({KEY})\s*$")
CLOSE_RE = re.compile(r"^\s*/metric\s*$")
LOOKS_LIKE_MARKER = re.compile(r"^\s*/?\s*metric\b")
UNCLOSED_RE = re.compile(r"<!--\s*/?\s*metric\b")
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
CODE_FORM_RE = re.compile(r"(`+)([^`](?:.*[^`])?)\1")
PLAIN_ESCAPES = set("\\`*_[]<>|~$&")

errors = []
warnings = []


def rel(path):
    return os.path.relpath(path, repo)


def split_lines(body):
    # Split on "\n" only (keeping it), so U+2028, NEL, and form feeds never
    # shift line numbers. A "\r" before "\n" stays part of the line ending.
    parts = body.split("\n")
    out = [part + "\n" for part in parts[:-1]]
    if parts[-1]:
        out.append(parts[-1])
    return out


def read_text(path):
    try:
        with open(path, encoding="utf-8", newline="") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError) as exc:
        errors.append(f"{rel(path)}: cannot read: {exc}")
        return None


def parse_entries(lines, src, first_lineno=1, skip=()):
    entries = []
    for lineno, raw in enumerate(lines, first_lineno):
        if lineno in skip:
            continue
        s = raw.rstrip("\r\n").strip()
        if not s or s.startswith("#"):
            continue
        m = ENTRY_RE.match(s)
        if not m or not m.group(2):
            errors.append(f"{src}:{lineno}: expected 'key = value' with a non-empty value")
            continue
        entries.append((m.group(1), m.group(2), lineno))
    return entries


# ---------------------------------------------------------------------------
# Metrics file (static keys + optional generated block)
# ---------------------------------------------------------------------------
metrics_rel = rel(metrics_path)
text = read_text(metrics_path) if os.path.exists(metrics_path) else None
lines = split_lines(text) if text is not None else []
eol = "\r\n" if text is not None and "\r\n" in text else "\n"
stripped = [ln.rstrip("\r\n") for ln in lines]
begins = [i for i, s in enumerate(stripped) if s == GEN_BEGIN]
ends = [i for i, s in enumerate(stripped) if s == GEN_END]
block = None
if begins or ends:
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        errors.append(f"{metrics_rel}: generated block needs exactly one '{GEN_BEGIN}' line followed by one '{GEN_END}' line")
    else:
        block = (begins[0], ends[0])

stale_block = False
if generate and not errors:
    with open(gen_out, encoding="utf-8") as fh:
        gen_lines = [ln.rstrip("\r\n") for ln in split_lines(fh.read())]
    gen_entries = parse_entries(gen_lines, f"{rel(generator)} output")
    new_block = [GEN_BEGIN + eol] + [f"{k} = {v}{eol}" for k, v, _ in gen_entries] + [GEN_END + eol]
    if block is not None:
        new_lines = lines[: block[0]] + new_block + lines[block[1] + 1 :]
    else:
        prefix = list(lines)
        if prefix and not prefix[-1].endswith("\n"):
            prefix[-1] += eol
        if prefix and prefix[-1].strip():
            prefix.append(eol)
        new_lines = prefix + new_block
    if new_lines != lines:
        stale_block = True
    lines = new_lines
    text = "".join(lines)

metrics = None
if text is not None and not errors:
    metrics = {}
    first_seen = {}
    for key, value, lineno in parse_entries(lines, metrics_rel):
        if key in metrics:
            errors.append(f"{metrics_rel}:{lineno}: duplicate key '{key}' (first defined on line {first_seen[key]})")
            continue
        metrics[key] = value
        first_seen[key] = lineno


# ---------------------------------------------------------------------------
# Markers in Markdown files
# ---------------------------------------------------------------------------
def render(value, content, table_row, where, key):
    m = CODE_FORM_RE.fullmatch(content)
    if m:
        if "`" in value:
            errors.append(f"{where}: value of '{key}' contains a backtick; it cannot go in a code span")
            return content
        inner = value.replace("|", "\\|") if table_row else value
        return m.group(1) + inner + m.group(1)
    return "".join("\\" + ch if ch in PLAIN_ESCAPES else ch for ch in value)


md_files = set()
with open(md_list, "rb") as fh:
    for raw_name in fh.read().split(b"\0"):
        if not raw_name:
            continue
        try:
            md_files.add(raw_name.decode("utf-8"))
        except UnicodeDecodeError:
            errors.append(f"{raw_name!r}: Markdown file name is not valid UTF-8")
md_files = sorted(md_files)

markers = []  # (file, lineno, key, content)
edits = {}  # path -> list of lines (with EOL) after replacement
used = set()
for md in md_files:
    path = os.path.join(repo, md)
    if not os.path.isfile(path):
        continue
    body = read_text(path)
    if body is None:
        continue
    md_lines = split_lines(body)
    out_lines = list(md_lines)
    in_fence, fence_char, fence_len, fence_line = False, "", 0, 0
    for idx, raw in enumerate(md_lines):
        lineno = idx + 1
        where = f"{md}:{lineno}"
        line = raw.rstrip("\r\n")
        eol_part = raw[len(line):]
        fm = FENCE_RE.match(line)
        if fm:
            marker, rest = fm.group(1), fm.group(2)
            if not in_fence and (marker[0] == "~" or "`" not in rest):
                in_fence, fence_char, fence_len, fence_line = True, marker[0], len(marker), lineno
                continue
            if in_fence and marker[0] == fence_char and len(marker) >= fence_len and not rest.strip():
                in_fence = False
                continue
        if in_fence:
            continue
        masked = list(line)
        for cm in CODESPAN_RE.finditer(line):
            for i in range(cm.start(), cm.end()):
                masked[i] = "\0"
        masked = "".join(masked)
        tokens = []
        for cm in COMMENT_RE.finditer(masked):
            inner = cm.group(1)
            om = OPEN_RE.match(inner)
            if om:
                tokens.append(("open", om.group(1), cm.start(), cm.end()))
            elif CLOSE_RE.match(inner):
                tokens.append(("close", None, cm.start(), cm.end()))
            elif LOOKS_LIKE_MARKER.match(inner):
                errors.append(f"{where}: malformed metric marker '<!--{inner}-->'")
        if UNCLOSED_RE.search(COMMENT_RE.sub(lambda m: " " * len(m.group(0)), masked)):
            errors.append(f"{where}: metric marker comment not closed on this line (markers must not span lines)")
            continue
        pairs = []
        open_tok = None
        for tok in tokens:
            if tok[0] == "open":
                if open_tok is not None:
                    errors.append(f"{where}: nested metric marker '{tok[1]}' inside '{open_tok[1]}'")
                    break
                open_tok = tok
            else:
                if open_tok is None:
                    errors.append(f"{where}: '<!-- /metric -->' without an opening marker")
                    break
                pairs.append((open_tok[1], open_tok[2], open_tok[3], tok[2]))
                open_tok = None
        else:
            if open_tok is not None:
                errors.append(f"{where}: metric marker '{open_tok[1]}' is not closed on the same line")
        if not pairs:
            continue
        table_row = line.lstrip().startswith("|")
        new_line = line
        for key, open_start, start, end in reversed(pairs):
            if line.lstrip().startswith("<!--"):
                errors.append(f"{where}: a marker must not start the line (CommonMark reads it as an HTML block)")
                continue
            content = line[start:end]
            markers.append((md, lineno, key, content))
            used.add(key)
            if metrics is None:
                continue
            if key not in metrics:
                errors.append(f"{where}: unknown metric key '{key}' (not in {metrics_rel})")
                continue
            expected = render(metrics[key], content, table_row, where, key)
            if expected != content:
                if mode == "check":
                    print(f"{where}: metric '{key}' is '{content}', expected '{expected}'")
                new_line = new_line[:start] + expected + new_line[end:]
        out_lines[idx] = new_line + eol_part
    if in_fence:
        errors.append(f"{md}:{fence_line}: fenced code block is never closed (markers after it would be skipped)")
    if out_lines != md_lines:
        edits[path] = out_lines

if markers and metrics is None and text is None:
    errors.append(f"{len(markers)} metric marker(s) found but the metrics file is missing: {metrics_rel}")

if metrics:
    for key in sorted(set(metrics) - used):
        warnings.append(f"key '{key}' in {metrics_rel} is used by no marker")

for w in warnings:
    print(f"[WARN] {w}", file=sys.stderr)
if errors:
    for e in errors:
        print(f"ERROR: {e}", file=sys.stderr)
    print(f">>> DOC METRICS: {len(errors)} error(s); nothing written <<<", file=sys.stderr)
    sys.exit(2)

if mode == "list":
    for md, lineno, key, content in markers:
        print(f"{md}:{lineno}: {key} = {content}")
    sys.exit(0)

if mode == "check":
    drift = len(edits)
    if stale_block:
        print(f"{metrics_rel}: generated block differs from {rel(generator)} output (run --generate)")
    if drift or stale_block:
        parts = []
        if stale_block:
            parts.append(f"generated block in {metrics_rel} is stale")
        if drift:
            parts.append(f"{drift} doc file(s) out of sync with {metrics_rel}")
        print(f">>> DOC METRICS DRIFT: {'; '.join(parts)} <<<")
        sys.exit(1)
    print(f"[PASS] {len(markers)} metric marker(s) in sync with {metrics_rel if text is not None else 'no metrics file'}.")
    sys.exit(0)

# Write phase: prepare every output, check every target is writable, then
# replace each file through a temp file in the same directory (os.replace).
outputs = []
if stale_block:
    outputs.append((metrics_path, text, f"{metrics_rel}: generated block refreshed"))
for path, out_lines in sorted(edits.items()):
    outputs.append((path, "".join(out_lines), rel(path)))
blocked = []
for path, _, _ in outputs:
    parent = os.path.dirname(path)
    if os.path.exists(path) and not os.access(path, os.W_OK):
        blocked.append(f"{rel(path)}: file is not writable")
    elif os.path.isdir(parent) and not os.access(parent, os.W_OK | os.X_OK):
        blocked.append(f"{rel(path)}: directory is not writable")
if blocked:
    for b in blocked:
        print(f"ERROR: {b}", file=sys.stderr)
    print(f">>> DOC METRICS: {len(blocked)} unwritable target(s); nothing written <<<", file=sys.stderr)
    sys.exit(2)
for path, content, label in outputs:
    parent = os.path.dirname(path)
    try:
        os.makedirs(parent, exist_ok=True)
        mode_bits = os.stat(path).st_mode & 0o7777 if os.path.exists(path) else 0o644
        fd, tmp = tempfile.mkstemp(prefix=".metrics-sync-", dir=parent)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
                fh.write(content)
            os.chmod(tmp, mode_bits)
            os.replace(tmp, path)
        except BaseException:
            if os.path.exists(tmp):
                os.unlink(tmp)
            raise
    except OSError as exc:
        print(f"ERROR: {rel(path)}: write failed: {exc}", file=sys.stderr)
        sys.exit(2)
    print(f"[SYNC] {label}")
print(f"[PASS] {len(markers)} metric marker(s); {len(edits)} file(s) rewritten.")
PY
